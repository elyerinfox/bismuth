//! The minimal WebAssembly interpreter: parse and run real wasm32 bytecode. Three modules cover
//! basics (locals + arithmetic), structured control flow (block/loop/br_if/br), and recursion
//! (call + if/else).

#![cfg(feature = "wasm")]

use bismuth::wasm::Module;

// (module (func (export "add") (param i32 i32) (result i32) local.get 0 local.get 1 i32.add))
const ADD: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, // magic + version
    0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f, // type: (i32,i32)->i32
    0x03, 0x02, 0x01, 0x00, // func: type 0
    0x07, 0x07, 0x01, 0x03, b'a', b'd', b'd', 0x00, 0x00, // export "add" -> func 0
    0x0a, 0x09, 0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6a, 0x0b, // code
];

// sumto(n) = n + (n-1) + ... + 1, via a block/loop with br_if/br.
const SUMTO: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x06, 0x01, 0x60, 0x01, 0x7f, 0x01, 0x7f, // (i32)->i32
    0x03, 0x02, 0x01, 0x00,
    0x07, 0x09, 0x01, 0x05, b's', b'u', b'm', b't', b'o', 0x00, 0x00,
    0x0a, 0x23, 0x01, 0x21, // code section, body size 0x21 = 33
    0x01, 0x01, 0x7f, // 1 local i32 (acc)
    0x02, 0x40, // block
    0x03, 0x40, // loop
    0x20, 0x00, 0x45, 0x0d, 0x01, // local.get n; i32.eqz; br_if 1 (break)
    0x20, 0x01, 0x20, 0x00, 0x6a, 0x21, 0x01, // acc += n
    0x20, 0x00, 0x41, 0x01, 0x6b, 0x21, 0x00, // n -= 1
    0x0c, 0x00, // br 0 (continue)
    0x0b, // end loop
    0x0b, // end block
    0x20, 0x01, // local.get acc
    0x0b, // end func
];

// Recursive factorial: fac(n) = if n<=1 {1} else {n * fac(n-1)}.
const FAC: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x06, 0x01, 0x60, 0x01, 0x7f, 0x01, 0x7f,
    0x03, 0x02, 0x01, 0x00,
    0x07, 0x07, 0x01, 0x03, b'f', b'a', b'c', 0x00, 0x00,
    0x0a, 0x19, 0x01, 0x17, // code, body size 0x17 = 23
    0x00, // no locals
    0x20, 0x00, 0x41, 0x01, 0x4c, // local.get n; i32.const 1; i32.le_s
    0x04, 0x7f, // if (result i32)
    0x41, 0x01, // then: 1
    0x05, // else
    0x20, 0x00, 0x20, 0x00, 0x41, 0x01, 0x6b, 0x10, 0x00, 0x6c, // n * fac(n-1)
    0x0b, // end if
    0x0b, // end func
];

#[test]
fn runs_basic_arithmetic() {
    let m = Module::parse(ADD).unwrap();
    assert_eq!(m.invoke("add", &[2, 3]).unwrap(), Some(5));
    assert_eq!(m.invoke("add", &[-10, 4]).unwrap(), Some(-6));
    assert_eq!(m.invoke("missing", &[]).err(), Some(bismuth::Error::NotFound));
}

#[test]
fn runs_a_loop() {
    let m = Module::parse(SUMTO).unwrap();
    assert_eq!(m.invoke("sumto", &[5]).unwrap(), Some(15));
    assert_eq!(m.invoke("sumto", &[10]).unwrap(), Some(55));
    assert_eq!(m.invoke("sumto", &[0]).unwrap(), Some(0));
}

#[test]
fn runs_recursion_with_if_else() {
    let m = Module::parse(FAC).unwrap();
    assert_eq!(m.invoke("fac", &[1]).unwrap(), Some(1));
    assert_eq!(m.invoke("fac", &[5]).unwrap(), Some(120));
    assert_eq!(m.invoke("fac", &[7]).unwrap(), Some(5040));
}

// (module (memory 1) (func (export "m") (result i32)
//   i32.const 8  i32.const 42  i32.store  i32.const 8  i32.load))
const MEM: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x05, 0x01, 0x60, 0x00, 0x01, 0x7f, // type ()->i32
    0x03, 0x02, 0x01, 0x00, // func type 0
    0x05, 0x03, 0x01, 0x00, 0x01, // memory: min 1 page
    0x07, 0x05, 0x01, 0x01, b'm', 0x00, 0x00, // export "m" -> func 0
    0x0a, 0x10, 0x01, 0x0e, // code: body 14 bytes
    0x00, 0x41, 0x08, 0x41, 0x2a, 0x36, 0x02, 0x00, 0x41, 0x08, 0x28, 0x02, 0x00, 0x0b,
];

// (module (import "wasi_snapshot_preview1" "proc_exit" (func (param i32)))
//   (func (export "_start") i32.const 7 call 0))
const EXIT: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x08, 0x02, 0x60, 0x01, 0x7f, 0x00, 0x60, 0x00, 0x00, // type0 (i32)->(), type1 ()->()
    0x02, 0x24, 0x01, 0x16, b'w', b'a', b's', b'i', b'_', b's', b'n', b'a', b'p', b's', b'h', b'o', b't', b'_', b'p',
    b'r', b'e', b'v', b'i', b'e', b'w', b'1', 0x09, b'p', b'r', b'o', b'c', b'_', b'e', b'x', b'i', b't', 0x00, 0x00,
    0x03, 0x02, 0x01, 0x01, // func type 1
    0x07, 0x0a, 0x01, 0x06, b'_', b's', b't', b'a', b'r', b't', 0x00, 0x01, // export "_start" -> func 1
    0x0a, 0x08, 0x01, 0x06, 0x00, 0x41, 0x07, 0x10, 0x00, 0x0b, // code: _start: const 7; call 0
];

#[test]
fn linear_memory_store_and_load() {
    let m = Module::parse(MEM).unwrap();
    assert_eq!(m.invoke("m", &[]).unwrap(), Some(42));
}

#[test]
fn wasi_proc_exit_sets_the_exit_code() {
    let m = Module::parse(EXIT).unwrap();
    assert_eq!(m.run_wasi().unwrap(), 7);
}
