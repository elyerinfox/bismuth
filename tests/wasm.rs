// A module that writes "hi" into memory, builds an iovec, calls WASI fd_write(stdout), and
// returns the byte count it reported (reads *nwritten back from memory).
// (import fd_write) (memory 1) (func (export "wtest") (result i32) ... )
const FDWRITE: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x0d, 0x02, 0x60, 0x04, 0x7f, 0x7f, 0x7f, 0x7f, 0x01, 0x7f, 0x60, 0x00, 0x01, 0x7f, // t0 (i32x4)->i32, t1 ()->i32
    0x02, 0x23, 0x01, 0x16, b'w', b'a', b's', b'i', b'_', b's', b'n', b'a', b'p', b's', b'h', b'o', b't', b'_', b'p',
    b'r', b'e', b'v', b'i', b'e', b'w', b'1', 0x08, b'f', b'd', b'_', b'w', b'r', b'i', b't', b'e', 0x00, 0x00,
    0x03, 0x02, 0x01, 0x01, // func type 1
    0x05, 0x03, 0x01, 0x00, 0x01, // memory 1
    0x07, 0x09, 0x01, 0x05, b'w', b't', b'e', b's', b't', 0x00, 0x01, // export "wtest" -> func 1
    0x0a, 0x32, 0x01, 0x30, // code: body 48 bytes
    0x00, // locals
    0x41, 0x08, 0x41, 0xe8, 0x00, 0x3a, 0x00, 0x00, // mem[8]='h'(104)
    0x41, 0x09, 0x41, 0xe9, 0x00, 0x3a, 0x00, 0x00, // mem[9]='i'(105)
    0x41, 0x00, 0x41, 0x08, 0x36, 0x02, 0x00, // iov.ptr(mem[0])=8
    0x41, 0x04, 0x41, 0x02, 0x36, 0x02, 0x00, // iov.len(mem[4])=2
    0x41, 0x01, 0x41, 0x00, 0x41, 0x01, 0x41, 0x14, // fd=1, iovs=0, iovs_len=1, nwritten=20
    0x10, 0x00, // call fd_write
    0x1a, // drop errno
    0x41, 0x14, 0x28, 0x02, 0x00, // return mem[20] (nwritten)
    0x0b,
];

#[test]
fn wasi_fd_write_gathers_iovecs_and_reports_bytes() {
    let m = Module::parse(FDWRITE).unwrap();
    // Writes "hi" to the console (fd 1) and reports 2 bytes written back through memory.
    assert_eq!(m.invoke("wtest", &[]).unwrap(), Some(2));
}

