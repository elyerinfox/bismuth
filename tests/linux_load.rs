//! The Linux loader's ELF layout: the hand-assembled hello binary parses to one R+X segment.
#![cfg(feature = "linux-abi")]

use bismuth::compat::linux::elf::{Elf, PF_R, PF_X};

// Hand-assembled aarch64 Linux ELF (181 bytes): write(1,msg,29); exit(0).
// msg = b'Hello from Linux on Bismuth!\n'
const HELLO_ELF: [u8; 181] = [
    0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x03, 0x00, 0xb7, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x78, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x38, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0xb5, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xb5, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x20, 0x00, 0x80, 0xd2, 0xe1, 0x00, 0x00, 0x10, 0xa2, 0x03, 0x80, 0xd2,
    0x08, 0x08, 0x80, 0xd2, 0x01, 0x00, 0x00, 0xd4, 0x00, 0x00, 0x80, 0xd2,
    0xa8, 0x0b, 0x80, 0xd2, 0x01, 0x00, 0x00, 0xd4, 0x48, 0x65, 0x6c, 0x6c,
    0x6f, 0x20, 0x66, 0x72, 0x6f, 0x6d, 0x20, 0x4c, 0x69, 0x6e, 0x75, 0x78,
    0x20, 0x6f, 0x6e, 0x20, 0x42, 0x69, 0x73, 0x6d, 0x75, 0x74, 0x68, 0x21,
    0x0a,
];

#[test]
fn hello_elf_parses_to_one_executable_segment() {
    let elf = Elf::parse(&HELLO_ELF).expect("parse");
    assert!(elf.pie, "built as ET_DYN (position-independent)");
    assert_eq!(elf.entry, 0x78, "entry just past the ELF+program headers");
    assert_eq!(elf.n_segments, 1);
    let s = elf.segments()[0];
    assert_eq!(s.vaddr, 0);
    assert_eq!(s.offset, 0);
    assert_eq!(s.flags & PF_X, PF_X, "code is executable");
    assert_eq!(s.flags & PF_R, PF_R, "code is readable");
    // The whole 181-byte file is one load segment.
    assert_eq!(s.filesz, HELLO_ELF.len());
    assert_eq!(s.memsz, HELLO_ELF.len());
    let (lo, hi) = elf.address_span();
    assert_eq!((lo, hi), (0, HELLO_ELF.len() as u64));
}
